#!/usr/bin/env node

import fs from 'fs';
import path from 'path';

/**
 * Embed API keys at compile time for production builds
 * This script generates a constants file with embedded API keys
 */

const EMBEDDED_CONSTANTS_FILE = 'src/utils/embeddedConstants.js';

// API Keys to embed (from environment variables)
const API_KEYS = {
  PROD: process.env.OPENSUBTITLES_API_KEY_PROD || process.env.VITE_OPENSUBTITLES_API_KEY_PROD || '',
  DEV:
    process.env.OPENSUBTITLES_API_KEY_DEV ||
    process.env.VITE_OPENSUBTITLES_API_KEY_DEV ||
    process.env.VITE_OPENSUBTITLES_API_KEY ||
    '',
};

// Generate the embedded constants file
function generateEmbeddedConstants() {
  const timestamp = new Date().toISOString();

  const content = `// Generated at compile time: ${timestamp}
// DO NOT EDIT THIS FILE MANUALLY - Generated by scripts/embed-api-keys.js

/**
 * Embedded API Constants
 * These are embedded at compile time for production builds
 */

// Embedded API Keys (one per backend environment)
export const EMBEDDED_OPENSUBTITLES_API_KEY_PROD = '${API_KEYS.PROD}';
export const EMBEDDED_OPENSUBTITLES_API_KEY_DEV = '${API_KEYS.DEV}';

// Build information
export const BUILD_TIMESTAMP = '${timestamp}';
export const HAS_EMBEDDED_KEYS = ${!!API_KEYS.PROD};

// Validation
export const validateEmbeddedKeys = () => {
  const errors = [];

  if (!EMBEDDED_OPENSUBTITLES_API_KEY_PROD) {
    errors.push('Production API key not embedded at compile time');
  }

  return {
    isValid: errors.length === 0,
    errors,
    hasEmbeddedKeys: HAS_EMBEDDED_KEYS
  };
};

console.log('📦 Embedded constants loaded:', {
  hasProdKey: !!EMBEDDED_OPENSUBTITLES_API_KEY_PROD,
  hasDevKey: !!EMBEDDED_OPENSUBTITLES_API_KEY_DEV,
  buildTime: BUILD_TIMESTAMP
});
`;

  // Ensure directory exists
  const dir = path.dirname(EMBEDDED_CONSTANTS_FILE);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }

  // Write the file
  fs.writeFileSync(EMBEDDED_CONSTANTS_FILE, content, 'utf8');

  console.log('✅ Generated embedded constants file:', EMBEDDED_CONSTANTS_FILE);
  console.log('📊 Embedded API keys:', {
    prod: API_KEYS.PROD ? '✅ Present' : '❌ Missing',
    dev: API_KEYS.DEV ? '✅ Present' : '❌ Missing',
    buildTime: timestamp,
  });

  return {
    file: EMBEDDED_CONSTANTS_FILE,
    hasKeys: !!API_KEYS.PROD,
    timestamp,
  };
}

// Main execution
if (import.meta.url === `file://${process.argv[1]}`) {
  console.log('🔑 Embedding API keys at compile time...');

  try {
    const result = generateEmbeddedConstants();

    if (!result.hasKeys) {
      console.warn('⚠️  Warning: no production API key found in environment variables');
      console.warn('   Set OPENSUBTITLES_API_KEY_PROD for production builds');
    }

    console.log('🎯 Embedded constants generation complete');
    process.exit(0);
  } catch (error) {
    console.error('❌ Failed to generate embedded constants:', error.message);
    process.exit(1);
  }
}

export { generateEmbeddedConstants };
